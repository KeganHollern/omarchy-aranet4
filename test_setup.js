const assert = require("node:assert/strict")
const fs = require("node:fs")
const vm = require("node:vm")
const context = vm.createContext({})
vm.runInContext(fs.readFileSync("Setup.js", "utf8"), context)
const parse = (value, action = "status") => context.parseResult(JSON.stringify(value), action)

assert.equal(parse({ ok: true, dependencies_ready: false }).dependencies_ready, false)
assert.equal(parse({ ok: true, dependencies_ready: true }).dependencies_ready, true)
assert.equal(parse({ ok: true, dependencies_ready: "true" }), null)
assert.equal(context.parseResult("{", "status"), null)
assert.equal(context.parseResult(" ".repeat(16385), "status"), null)
assert.equal(parse([]), null)
assert.equal(parse({ ok: false, error: "bad\nmessage\u0000" }).error, "badmessage")
assert.equal(parse({ ok: false, error: "x".repeat(500) }).error.length, 320)

const device = { address: "aa:bb:cc:dd:ee:ff", name: "Aranet4\u0000 example", readable: true }
let result = parse({ ok: true, devices: [device, device] }, "discover")
assert.equal(result.devices.length, 1)
assert.equal(result.devices[0].address, "AA:BB:CC:DD:EE:FF")
assert.equal(result.devices[0].name, "Aranet4 example")
assert.equal(parse({ ok: true, devices: [{ ...device, readable: false }] }, "discover").devices[0].readable, false)
assert.equal(parse({ ok: true, devices: [{ ...device, address: "bad" }] }, "discover"), null)
assert.equal(parse({ ok: true, devices: [{ ...device, readable: "true" }] }, "discover"), null)
assert.equal(parse({ ok: true, devices: Array(17).fill(device) }, "discover"), null)
assert.equal(parse({ ok: true, devices: [] }, "discover").devices.length, 0)
console.log("Setup protocol checks passed.")
